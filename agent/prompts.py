def issue_prompt(user_input: str, article: str | None, web_digest: str | None) -> str:
    parts = ["아래 사회 현안을 구조화하세요: 본질 진단, 쟁점, 연루된 사회 계층, 이해관계 충돌 양상."]
    parts.append(f"<input>\n{user_input}\n</input>")
    if article:
        parts.append(f"<article>\n{article}\n</article>")
    if web_digest:
        parts.append(f"<web_research>\n{web_digest}\n</web_research>")
    parts.append(
        "표면 현상과 근본 원인을 분리해 서술하세요. 근본 원인은 구조·제도·가치·신뢰 중 어디에 뿌리가 있는지 짚습니다."
    )
    return "\n\n".join(parts)


def research_prompt(user_input: str, article_title: str | None) -> str:
    topic = article_title or user_input
    return f"""다음 사회 현안에 대한 대중의 시각을 웹에서 조사하세요.

현안: {topic}

조사 대상: 최근 뉴스 보도, YouTube의 요약·해설 영상과 댓글 담론, 전문 블로그·칼럼.
정리 방식: 700~1000자. 쟁점별로 주된 입장 2~3개, 자주 쓰이는 프레임, 감정의 결(분노·불안·냉소 등)을 \
출처 유형(뉴스/유튜브/블로그)과 함께 적습니다. 검색에서 확인되지 않은 것은 추정이라고 밝히고, 특정 입장을 편들지 않습니다."""


